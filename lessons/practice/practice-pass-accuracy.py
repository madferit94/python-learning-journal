# 3. 반복문 안에서 계산하기
# for passes in completed_passes:
#     accuracy_passes = passes / 60 * 100
#     print(accuracy_passes)
#
# 왜 passes를 쓰나요?
# completed_passes는 리스트 전체이므로 / 60으로 나눌 수 없습니다.
# passes는 48, 42, 30 같은 숫자 하나이므로 계산할 수 있습니다.
# accuracy_passes: 이번에 계산한 성공률을 저장하는 변수입니다.
# 사용자 변수명을 유지했습니다. 문제에 있던 pass_accuracy와 달라도 괜찮습니다.
# /는 나눗셈, * 100은 비율을 백분율로 바꾸는 계산입니다.
# 각 선수의 시도 수가 모두 60회라는 가정입니다.
# 계산 줄과 출력 줄을 들여써야 매번 새 값으로 계산·출력합니다.
# 사용자 예상·기록: 80, 70, 50. 실제 Python 표기는 80.0, 70.0, 50.0입니다.


# 4. 최종 코드 — 계산과 등급 분류
# 사용자 제출 코드: [48, 42, 30] → [48, 36, 30]으로 조건을 변경함.
# 두 번째 성공률·등급 사용자 예상: 60, 보통 → 올바른 예상입니다.
# 이번 실행 예상:
# 80.0
# 우수
# 60.0
# 보통
# 50.0
# 개선 필요
completed_passes = [48, 36, 30]

for passes in completed_passes:
    accuracy_passes = passes / 60 * 100
    print(accuracy_passes)

    # if / elif / else가 for 안에 있어 각 기록의 등급을 판단합니다.
    # 처음 참인 조건 하나만 실행합니다. 높은 기준부터 검사합니다.
    if accuracy_passes >= 80:
        print("우수")
    elif accuracy_passes >= 60:  # 60도 포함합니다.
        print("보통")
    else:
        print("개선 필요")
# 원본에서는 위 최종 코드가 실행 상태이고 앞 문제들은 주석 처리되어 있었습니다.


