# CSV 열 선택과 조건 필터 실습
# 실행할 때 CSV 경로를 인수로 전달합니다.
# 주제: CSV 불러오기 → 열 선택 → 조건에 맞는 행 선택
# AI의 설명과 오류 수정 도움을 받아 작성·실행한 코드입니다.


# 1. pandas 불러오기
# pandas는 표 형태의 데이터를 다루는 도구입니다.
# as pd는 pandas를 pd라는 짧은 이름으로 사용한다는 뜻입니다.
import sys
import pandas as pd


# 2. CSV를 읽고 표의 처음 5행 확인하기
# pd.read_csv("경로")는 CSV 파일을 읽습니다.
# df에는 불러온 표 전체가 저장됩니다.
# head()는 그 표의 처음 5행을 보여줍니다.
df = pd.read_csv(
    sys.argv[1]
)
print(df.head())


# 3. 선수 이름 열 전체 확인하기
# df["player_name"]은 표에서 선수 이름 열만 선택합니다.
# 데이터가 많으면 화면에는 중간 부분이 ...으로 생략됩니다.
print(df["player_name"])


# 4. 선수 이름 열의 처음 5개 값 확인하기
# 같은 열에 head()를 붙이면 처음 5개 값만 보여줍니다.
# 이번 출력에서는 Alex Paulsen이 다섯 번 나왔습니다.
print(df["player_name"].head())


# 5. 득점 열의 처음 5개 값 확인하기
# "goals"는 실제 컬럼 이름이므로 따옴표가 필요합니다.
# 처음 5개 값은 모두 0이었습니다.
print(df["goals"].head())


# 6. 10골 이상인 행 선택하기
# 안쪽 df["goals"] >= 10은 각 행이 조건을 만족하는지 판단합니다.
# 바깥 df[조건]은 조건이 True인 행만 선택합니다.
# 선택한 표를 goals_10_plus라는 새 변수에 저장합니다.
goals_10_plus = df[df["goals"] >= 10]

# 선택한 표의 처음 5행을 출력합니다.
print(goals_10_plus.head())


# 7. 20골 이상인 행 선택하기
# 앞의 코드에서 기준을 10에서 20으로 바꿨습니다.
# 원래 표 df는 그대로 두고 선택 결과를 새 변수에 저장합니다.
goals_20_plus = df[df["goals"] >= 20]
print(goals_20_plus.head())

# 제공한 출력에서 득점 값은 22, 39, 29, 21, 26이었습니다.
# 득점 순 상위 5명이 아니라 조건에 맞는 행 중 처음 5행입니다.


# 8. 변수에 따로 저장하지 않고 바로 출력하기
# 7번과 같은 조건을 적용하고, 바로 처음 5행을 출력합니다.
# 따라서 7번의 출력과 같은 결과가 한 번 더 나옵니다.
print(df[df["goals"] >= 20].head())

# 두 방식의 차이:
# 7번은 선택 결과를 goals_20_plus에 저장해 다시 사용할 수 있습니다.
# 8번은 선택 결과를 새 변수에 저장하지 않고 바로 출력합니다.
# 지금은 7번처럼 저장과 출력을 나누는 방식으로 연습합니다.


