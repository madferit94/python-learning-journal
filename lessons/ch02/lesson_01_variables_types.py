# 2. 핵심 개념
# 변수: 값을 가리키는 이름. a와 value는 직접 정한 변수 이름입니다.
# =: 오른쪽 값을 왼쪽 변수 이름에 대입합니다. 같음을 비교하는 기호는 ==입니다.
# int: 정수형. 5, 7처럼 따옴표 없는 정수 값입니다.
# str: 문자열형. "foo", "7", "value"처럼 따옴표로 감싼 글자입니다.
# type(값): 값의 자료형을 반환하는 함수입니다.
# print(값): 전달받은 값을 화면에 보여주는 함수입니다.
# print(type(value))는 안쪽 type(value)로 자료형을 알아낸 뒤 그 결과를 출력합니다.
# 함수 이름 뒤의 ()는 함수를 실행할 때 씁니다.
# 문자열을 다른 값으로 다시 대입하는 것과 숫자로 변환하는 것은 다릅니다.
# 오늘 코드는 형 변환 함수를 쓴 것이 아니라 같은 변수에 다른 값을 대입한 것입니다.


# 3. 교재 예제와 사용자 실행 확인
# 원본 노트북은 type(a)로 결과를 확인합니다.
# .py 파일에서는 결과를 화면에 보이도록 print(type(a))로 바꿨습니다.
#
# a = 5
# print(type(a))
# a = "foo"
# print(type(a))
# print(a)
#
# 사용자 예상: 첫 번째 정수형, 두 번째 문자열형.
# 사용자 제공 출력:
# <class 'int'>
# <class 'str'>
# foo
# 사용자 설명: 마지막에 foo를 a에 넣었으므로 foo가 나올 것 같다.
# 판정: 예측과 설명이 맞고, 실제 출력도 일치했습니다.
# a에 5와 "foo"가 동시에 저장되는 것이 아니라 현재 값이 바뀝니다.


# 4. 사용자가 작성한 최종 코드 — 여기만 실행됩니다.
# 원래 문제는 숫자 7 → 문자열 "7" 순서였습니다.
# 사용자는 반대 순서로 작성했습니다. 순서는 다르지만 코드와 결과는 맞습니다.
value = "7"
print(type(value))

value = 7
print(type(value))

print(value)
print("value")
# 첫 대입: value에 글자 "7" 저장 → str.
# 두 번째 대입: 같은 value에 숫자 7 저장 → int.
# print(value): 현재 저장된 값 7을 출력.
# print("value"): 변수 내용을 찾지 않고 글자 value를 그대로 출력.


# 5. 사용자 실제 출력과 실행 전 설명
# <class 'str'>
# <class 'int'>
# 7
# value
#
# 실행 전 사용자 설명:
# "위에는 value에 입력된 값 7을, 밑에는 value를 출력할 것 같다."
# 판정: 맞습니다. 예측과 공유한 실제 출력이 일치했습니다.
# 따옴표는 코드에서 문자열을 표시하는 기호라 보통 print 출력에는 함께 나오지 않습니다.


# 6. 처음 시도와 피드백 — 결과만으로 단정하지 않기
# 초기에는 7만 나온 실행 결과를 공유했습니다.
# 피드백: 숫자 7과 문자열 "7"은 print로 보면 둘 다 7로 보여 자료형을 알 수 없습니다.
# 자료형 확인에는 type()이 필요하다는 힌트와 print(type(value)) 예제를 받았습니다.
#
# 이후 str만 나온 결과, int만 나온 결과를 차례로 공유했습니다.
# 그 출력만으로 두 대입이 한 실행에서 함께 있었는지는 확인할 수 없었습니다.
# 코치가 두 대입과 두 출력을 한 파일에서 실행하도록 안내했습니다.
#
# 최종적으로 문자열 → 숫자 순서의 코드와 str → int 출력을 함께 확인했습니다.
# 실제 예외 메시지는 이번 수업에서 공유되지 않았습니다.
# 따라서 TypeError·NameError 등을 새로 만들어 오류 이력에 넣지 않습니다.
# 이것은 예제·힌트를 참고해 완성한 기록이며 완전 독립 수행으로 바꾸지 않습니다.


