# [사용자 수정]
# numeric_total = first_number + second_number  # 변환한 정수끼리 더해 15를 저장합니다.
# 수정 후 실제 출력: 15.
#
# [자료형 비교의 중간 시도]
# print(type(first_number))  # 변환한 값의 자료형 int를 확인합니다.
# print(type(second_number))  # 두 번째 변환 결과도 int인지 확인합니다.
# 출력은 int / int로 맞았지만 원래 문자열과 변환 결과를 비교하지는 못했습니다.
