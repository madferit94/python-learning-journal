# 문제 2 — 배열의 모양 확인
import numpy as np  # 이 문제에서 사용할 NumPy를 불러옵니다.
shape_01 = np.array([6, 7.5, 8, 0, 1])  # 값 5개로 1차원 배열을 만듭니다.
shape_02 = np.array([[1, 2, 3, 4], [5, 6, 7, 8]])  # 값 4개씩 담은 두 행으로 배열을 만듭니다.
print(shape_01.shape)  # 한 방향에 값이 몇 개 있는지 확인합니다.
print(shape_02.shape)  # 행과 열이 각각 몇 개인지 확인합니다.

# (5,)
# (2, 4)
# `shape.01`은 변수 이름에 점을 넣어 `SyntaxError`가 났습니다. `shape_01`로 바꿨습니다. `np.arrat`은 오타라 `AttributeError`가
# 났고 `np.array`로 바꿨습니다. `data.shape_01`에서 `data`는 정의하지 않아 `NameError`가 났습니다. 실제 배열 이름 뒤에 `.shape`를 붙여
# 해결했습니다.
# `(5,)`는 값이 5개인 1차원 배열의 모양입니다. 끝의 쉼표는 값 하나를 담은 튜플이라는 표시입니다. `(2, 4)`는 2행 4열입니다. 예를 들어 `[[1, 2, 3, 4],
# [5, 6, 7]]`처럼 안쪽 길이가 다르면 일반적인 숫자 배열을 만들 수 없어 `np.array()`에서 `ValueError`가 납니다. 코치가 NumPy 1.26.4에서
# 확인했습니다.

