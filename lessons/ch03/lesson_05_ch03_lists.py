# 수업 05 — 교재 3장 리스트 기초
# 리스트에서 값을 꺼내고, 추가한 뒤 여러 건의 총금액을 계산합니다.

# 1. 위치로 값 꺼내기
quantities = [2, 5, 8]  # 세 건의 수량을 리스트 하나에 저장합니다.
print(quantities[1])  # 위치 번호 1에 있는 두 번째 값을 출력합니다.

# 2. 리스트에 값 추가하기
quantities.append(3)  # 리스트 끝에 수량 3을 추가합니다.
print(quantities)  # 추가한 값까지 포함된 리스트를 출력합니다.

# 3. 반복문으로 총금액 계산하기
price = 35  # 모든 수량에 적용할 가격을 정합니다.
for quantity in quantities:  # 리스트에서 수량을 하나씩 꺼냅니다.
    amount = price * quantity  # 이번 수량에 가격을 곱합니다.
    print(amount)  # 이번 총금액을 한 줄에 출력합니다.

# 정리한 파일을 실행해 확인한 출력
# 5
# [2, 5, 8, 3]
# 70
# 175
# 280
# 105
